// Writes src/catalog.ts from the Orca installed here: the coding agents Orca
// can launch, and each agent's models with their effort levels, as Orca's own
// launch catalogue lists them. A Buzz plugin can run only Orca's CLI, which
// has no command that lists these, so the plugin carries a copy; run this
// after an Orca update and commit the result.
//   node scripts/catalog.mjs [/Applications/Orca.app]
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";

const app = process.argv[2] ?? "/Applications/Orca.app";
const shared = join(app, "Contents/Resources/app.asar.unpacked/out/shared");
const require = createRequire(import.meta.url);
const { TUI_AGENT_CONFIG } = require(join(shared, "agent-launch/catalog/tui-agent-config.js"));
const { getAgentSessionOptionCatalog } = require(
  join(shared, "agent-session/options/agent-session-option-catalog.js"),
);
const version = execFileSync("defaults", ["read", join(app, "Contents/Info.plist"), "CFBundleShortVersionString"], {
  encoding: "utf8",
}).trim();

// Orca names agents in its renderer; these are the names people know them by.
const NAMES = {
  claude: "Claude Code",
  "claude-agent-teams": "Claude Code (agent teams)",
  codex: "Codex",
  opencode: "OpenCode",
  opencode2: "OpenCode 2",
  gemini: "Gemini CLI",
  cursor: "Cursor",
  copilot: "GitHub Copilot",
  goose: "Goose",
  amp: "Amp",
  aider: "Aider",
  pi: "Pi",
  omp: "OMP",
  "qwen-code": "Qwen Code",
  "mistral-vibe": "Mistral Vibe",
  "command-code": "Command Code",
  "prime-agent": "Prime Agent",
  "qoder-cn": "Qoder (China)",
  "mimo-code": "MiMo Code",
};
const FIRST = ["claude", "codex", "opencode", "gemini", "cursor", "copilot"];
const title = (id) =>
  NAMES[id] ?? id.split("-").map((word) => word[0].toUpperCase() + word.slice(1)).join(" ");

const ids = Object.keys(TUI_AGENT_CONFIG).sort((a, b) => {
  const [x, y] = [FIRST.indexOf(a), FIRST.indexOf(b)];
  if (x !== -1 || y !== -1) return (x === -1 ? 99 : x) - (y === -1 ? 99 : y);
  return title(a).localeCompare(title(b));
});
const agents = ids.map((id) => ({ id, label: title(id) }));

const models = {};
for (const id of ids) {
  let catalogue;
  try {
    catalogue = getAgentSessionOptionCatalog(id);
  } catch {
    continue;
  }
  const listed = (catalogue?.models ?? []).map((model) => {
    const effort = (model.options ?? []).find(
      (option) => option.id === "effort" || option.category === "thought_level",
    );
    const choices = effort?.kind?.type === "select" ? effort.kind.choices : [];
    return {
      id: model.id,
      label: model.label ?? model.id,
      ...(model.isDefault && { isDefault: true }),
      efforts: choices.map((choice) => ({ id: String(choice.value), label: String(choice.label ?? choice.value) })),
      ...(effort?.kind?.defaultValue !== undefined && { defaultEffort: String(effort.kind.defaultValue) }),
    };
  });
  if (listed.length) models[id] = listed;
}

const out = `// GENERATED by scripts/catalog.mjs from Orca ${version}. Do not edit by hand:
// run \`npm run catalog\` after an Orca update and commit the result.
// The coding agents Orca can launch, and each one's models and effort levels.

export type CatalogChoice = Readonly<{ id: string; label: string }>;
export type CatalogModel = Readonly<{
  id: string;
  label: string;
  isDefault?: true;
  efforts: readonly CatalogChoice[];
  defaultEffort?: string;
}>;

export const ORCA_VERSION = ${JSON.stringify(version)};

export const AGENTS: readonly CatalogChoice[] = ${JSON.stringify(agents, null, 2)};

export const MODELS: Readonly<Record<string, readonly CatalogModel[]>> = ${JSON.stringify(models, null, 2)};
`;
const file = new URL("../src/catalog.ts", import.meta.url);
const before = (() => {
  try {
    return readFileSync(file, "utf8");
  } catch {
    return "";
  }
})();
writeFileSync(file, out);
console.log(`src/catalog.ts: ${agents.length} agents, models for ${Object.keys(models).join(", ")} (Orca ${version})${before === out ? ", unchanged" : ""}`);
